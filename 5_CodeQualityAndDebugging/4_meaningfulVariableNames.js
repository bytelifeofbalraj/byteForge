// Create a function named `calculateRectangleArea` that takes two parameters with descriptive names: `width` and `height`. The function should return the area. Call it with arguments 15 and 10, and log the result.

function calculateRectangleArea(width, height) {
    return width * height;
}

const rectangleWidth = 15;
const rectangleHeight = 10;
const area = calculateRectangleArea(rectangleWidth, rectangleHeight);


console.log(`The area of the rectangle is: ${area}`); // Output: The area of the rectangle is: 150


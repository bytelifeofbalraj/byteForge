// Create four variables: `str` = 'hello', `num` = 42, `bool` = true, and `arr` = [1, 2, 3]. Use typeof to log the type of each variable in the format: 'str is string'

const str = 'hello';
const num = 42;
const bool = true;
const arr = [1, 2, 3];

console.log(`str is ${typeof str}`); // Output: str is string
console.log(`num is ${typeof num}`); // Output: num is number
console.log(`bool is ${typeof bool}`); // Output: bool is boolean
console.log(`arr is ${typeof arr}`); // Output: arr is object (arrays are of type 'object' in JavaScript)   


// Create an object named `car` with properties: `brand` = 'Toyota', `model` = 'Camry', and `year` = 2020. Access and log the `brand` property using dot notation, then access and log the `model` property using bracket notation.

const car = {
    brand: 'Toyota',
    model: 'Camry',
    year: 2020
};

// Accessing properties using dot notation
console.log(car.brand); // Output: Toyota

// Accessing properties using bracket notation
console.log(car['model']); // Output: Camry 
